// Generates the Bustamam Technology wordmark as outlined vector paths, so it
// renders identically on every device (no dependency on installed fonts).
//
//   bun scripts/build-wordmark.ts
//
// Writes:
//   src/components/wordmark-data.ts         (used by BrandLogo.astro)
//   public/bustamam-technology-wordmark.svg (canonical standalone logo)
//
// Layout: BUSTAMAM in Archivo Black; TECHNOLOGY in Archivo Medium, letter-
// spaced so its ink spans exactly BUSTAMAM's ink, left edge to right edge.
// Each letter is its own path so the wordmark can be animated per letter.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const loadFont = (spec: string) => {
  const buf = readFileSync(require.resolve(spec));
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
};

const black = loadFont('@fontsource/archivo-black/files/archivo-black-latin-400-normal.woff');
const regular = loadFont('@fontsource/archivo/files/archivo-latin-500-normal.woff');

const round = (n: number) => Math.round(n * 100) / 100;

const TOP = { text: 'BUSTAMAM', font: black, size: 256, tracking: -4 };
const SUB = { text: 'TECHNOLOGY', font: regular, size: 84 };
const GAP = 40; // space between BUSTAMAM's baseline and TECHNOLOGY's cap top
const PAD = 8;

type Letter = { ch: string; d: string; x1: number; x2: number };

/** Lay a line out glyph by glyph at baseline 0, with fixed extra tracking. */
function lineLetters(font: opentype.Font, text: string, size: number, tracking: number): Letter[] {
  const scale = size / font.unitsPerEm;
  const glyphs = [...text].map((ch) => font.charToGlyph(ch));
  let x = 0;
  return glyphs.map((g, i) => {
    const path = g.getPath(round(x), 0, size);
    const bb = path.getBoundingBox();
    const letter = { ch: text[i], d: path.toPathData(2), x1: bb.x1, x2: bb.x2 };
    let adv = (g.advanceWidth ?? 0) * scale;
    if (i + 1 < glyphs.length) adv += font.getKerningValue(g, glyphs[i + 1]) * scale;
    x += adv + tracking;
    return letter;
  });
}

const inkWidth = (ls: Letter[]) => ls[ls.length - 1].x2 - ls[0].x1;

const top = lineLetters(TOP.font, TOP.text, TOP.size, TOP.tracking);
const targetWidth = inkWidth(top);

// Ink width is linear in tracking: solve for the tracking that matches BUSTAMAM.
const base = lineLetters(SUB.font, SUB.text, SUB.size, 0);
const subTracking = (targetWidth - inkWidth(base)) / (SUB.text.length - 1);
const sub = lineLetters(SUB.font, SUB.text, SUB.size, subTracking);

const capHeight = (font: opentype.Font, size: number) =>
  ((font.tables.os2?.sCapHeight as number) ?? font.charToGlyph('H').yMax ?? 0) * (size / font.unitsPerEm);

const topCap = capHeight(TOP.font, TOP.size);
const subCap = capHeight(SUB.font, SUB.size);

// Place both lines: left ink edge at PAD, BUSTAMAM's cap top at PAD.
const topDx = PAD - top[0].x1;
const subDx = PAD - sub[0].x1;
const topBaseline = PAD + topCap;
const subBaseline = topBaseline + GAP + subCap;

// Re-lay out at final positions so path data is absolute (no transforms).
function placed(letters: Letter[], font: opentype.Font, text: string, size: number, tracking: number, dx: number, baseline: number) {
  const scale = size / font.unitsPerEm;
  const glyphs = [...text].map((ch) => font.charToGlyph(ch));
  let x = dx;
  return glyphs.map((g, i) => {
    const d = g.getPath(round(x), round(baseline), size).toPathData(2);
    let adv = (g.advanceWidth ?? 0) * scale;
    if (i + 1 < glyphs.length) adv += font.getKerningValue(g, glyphs[i + 1]) * scale;
    x += adv + tracking;
    return { ch: letters[i].ch, d };
  });
}

const topPaths = placed(top, TOP.font, TOP.text, TOP.size, TOP.tracking, topDx, topBaseline);
const subPaths = placed(sub, SUB.font, SUB.text, SUB.size, subTracking, subDx, subBaseline);

const width = Math.ceil(targetWidth + PAD * 2);
const height = Math.ceil(subBaseline + PAD);
const viewBox = `0 0 ${width} ${height}`;

const data = `// Generated by scripts/build-wordmark.ts — do not edit by hand.
export const WORDMARK_VIEWBOX = '${viewBox}';
export const WORDMARK_WIDTH = ${width};
export const WORDMARK_HEIGHT = ${height};
export const WORDMARK_TOP: { ch: string; d: string }[] = ${JSON.stringify(topPaths, null, 2)};
export const WORDMARK_SUB: { ch: string; d: string }[] = ${JSON.stringify(subPaths, null, 2)};
`;
writeFileSync(new URL('../src/components/wordmark-data.ts', import.meta.url), data);

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${viewBox}" role="img" aria-label="Bustamam Technology">
  <style>
    .logo-text { fill: #1f2328; }
    @media (prefers-color-scheme: dark) {
      .logo-text { fill: #eceae3; }
    }
  </style>
  <g class="logo-text">
${[...topPaths, ...subPaths].map((p) => `    <path d="${p.d}"/>`).join('\n')}
  </g>
</svg>
`;
writeFileSync(new URL('../public/bustamam-technology-wordmark.svg', import.meta.url), svg);

console.log(`viewBox ${viewBox}; BUSTAMAM ink ${round(targetWidth)}; TECHNOLOGY tracking ${round(subTracking)}`);
